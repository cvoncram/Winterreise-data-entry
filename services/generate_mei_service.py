import os
import zipfile
import uuid
from pathlib import Path
from datetime import datetime, timezone
from lxml import etree

NS = {"mei": "http://www.music-encoding.org/ns/mei"}


def _sanitize_filename_part(s: str) -> str:
    s = str(s).strip().replace(" ", "_")
    return "".join(c for c in s if c.isalnum() or c in ("-", "_"))


def _make_manifestation_element(manifestation_id: str, label: str, pianist_text: str, creation_type: str, singer_text: str):
    M = "{http://www.music-encoding.org/ns/mei}"
    manifestation = etree.Element(f"{M}manifestation")
    manifestation.set("{http://www.w3.org/XML/1998/namespace}id", manifestation_id)
    manifestation.set("label", label)
    manifestation.set("n", "1")
    manifestation.set("type", "audio_recording")

    editionStmt = etree.SubElement(manifestation, f"{M}editionStmt")
    edition = etree.SubElement(editionStmt, f"{M}edition")
    bibl = etree.SubElement(edition, f"{M}bibl")

    title = etree.SubElement(bibl, f"{M}title")
    title.text = (
        "Winterreise : [Liederzyklus nach Gedichten von Wilhelm Müller; "
        "D 911 (op. 89)] / Franz Schubert"
    )

    identifier = etree.SubElement(bibl, f"{M}identifier")
    identifier.set("auth", "GND")
    identifier.set("auth.uri", "https://d-nb.info/990256839")

    # singer
    pers_singer = etree.SubElement(bibl, f"{M}persName")
    pers_singer.set("role", "singer")
    pers_singer.text = singer_text

    # pianist
    pers_pianist = etree.SubElement(bibl, f"{M}persName")
    pers_pianist.set("role", "pianist")
    pers_pianist.text = pianist_text

    creation = etree.SubElement(bibl, f"{M}creation")
    creation.set("type", creation_type)
    creation.text = creation_type

    return manifestation


def _make_appinfo_fragment(app_label="MEI-Generator", app_version="1.0"):
    M = "{http://www.music-encoding.org/ns/mei}"
    appinfo = etree.Element(f"{M}appInfo")
    appinfo.set("{http://www.w3.org/XML/1998/namespace}id", f"appinfo-{uuid.uuid4().hex[:8]}")

    application = etree.SubElement(appinfo, f"{M}application")
    application.set("{http://www.w3.org/XML/1998/namespace}id", f"app-{uuid.uuid4().hex[:8]}")
    now = datetime.now(timezone.utc).replace(microsecond=0).isoformat()

    application.set("startdate", now)
    application.set("enddate", now)
    application.set("version", app_version)

    name_el = etree.SubElement(application, f"{M}name")
    name_el.text = app_label

    p_el = etree.SubElement(application, f"{M}p")
    p_el.text = f"Generated by {app_label} {app_version} on {now}."

    return appinfo


def generate_mei_package(
    manifestation_id: str,
    year: str,
    pianist: str,
    creation_type: str,
    singer: str,
    templates_dir="resources/mei_templates",
    out_dir="temp_generated_mei"
):
    templates_path = Path(templates_dir)
    template_files = sorted(templates_path.glob("*.mei"))[:24]

    run_id = uuid.uuid4().hex
    run_out_dir = Path(out_dir) / run_id
    run_out_dir.mkdir(parents=True, exist_ok=True)

    # derive filename base
    pianist_last = pianist.split()[-1]
    safe_pianist_last = _sanitize_filename_part(pianist_last)

    label = f"{year}_{pianist_last}"

    for idx, tpl_path in enumerate(template_files, start=1):
        tree = etree.parse(str(tpl_path))
        root = tree.getroot()

        # create manifestation
        manifestation_el = _make_manifestation_element(
            manifestation_id=manifestation_id,
            label=label,
            pianist_text=pianist,
            creation_type=creation_type,
            singer_text=singer
        )

        # Insert manifestation
        manifest_lists = root.xpath(".//mei:manifestationList", namespaces=NS)
        if manifest_lists:
            manifest_lists[0].append(manifestation_el)
        else:
            # fallback – create manifestationList inside sourceDesc
            src_desc = root.xpath(".//mei:sourceDesc", namespaces=NS)
            if src_desc:
                ml = etree.SubElement(src_desc[0], "{http://www.music-encoding.org/ns/mei}manifestationList")
                ml.append(manifestation_el)
            else:
                root.append(manifestation_el)

        # Insert appInfo into encodingDesc
        enc = root.xpath(".//mei:meiHead//mei:encodingDesc", namespaces=NS)
        if enc:
            enc[0].append(_make_appinfo_fragment())
        else:
            mh = root.xpath(".//mei:meiHead", namespaces=NS)
            if mh:
                ed = etree.SubElement(mh[0], "{http://www.music-encoding.org/ns/mei}encodingDesc")
                ed.append(_make_appinfo_fragment())
            else:
                root.append(_make_appinfo_fragment())

        filename = f"{year}_{safe_pianist_last}_{idx}_Audio_Data.xml"
        outpath = run_out_dir / filename
        tree.write(str(outpath), xml_declaration=True, encoding="utf-8", pretty_print=True)

    # package into zip
    zip_path = Path(out_dir) / f"{run_id}.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for file in run_out_dir.glob("*.xml"):
            zf.write(file, file.name)

    return str(zip_path)
