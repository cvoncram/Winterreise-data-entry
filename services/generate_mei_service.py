import zipfile
import uuid
from pathlib import Path
from datetime import datetime
from lxml import etree
from config import TEMP_MEI_DIR

NS = {"mei": "http://www.music-encoding.org/ns/mei"}

def _sanitize_filename_part(s: str) -> str:
    s = (s or "").strip().replace(" ", "_")
    return "".join(c for c in s if c.isalnum() or c in ("-", "_")) or "unknown"

CREATION_MAP = {
    "Recital": ("Live - Recital", "Recital"),
    "Studio": ("Studio - Recording", "Studio Recording"),
    "Radio Broadcast": ("Studio - Radio Broadcast", "Radio Broadcast"),
    "TV Production": ("Live - TV Production", "TV Production"),
}


def _make_appinfo_fragment():
    """
    Returns an <appInfo> element containing <application> with metadata.
    """
    M = "{http://www.music-encoding.org/ns/mei}"
    appinfo = etree.Element(f"{M}appInfo")
    application = etree.SubElement(appinfo, f"{M}application")
    application.set("{http://www.w3.org/XML/1998/namespace}id", "mei_generator")
    application.set("version", "1.0")

    name_el = etree.SubElement(application, f"{M}name")
    name_el.text = "MEI-XML generator tool"

    p_el = etree.SubElement(application, f"{M}p")
    date_str = datetime.now().strftime("%B %d, %Y")
    p_el.text = f"This file was generated by MEI-XML generator on {date_str}."

    return appinfo

def generate_mei_package(
    manifestation_id: str,
    manifestation_n: int,
    year: str,
    pianist_first: str,
    pianist_last: str,
    gnd_uid: str,
    context: str,
    label_addition: str,
    templates_dir,
    out_dir
):

    templates_path = Path(templates_dir).resolve() 
    out_dir = Path(out_dir).resolve()
    if not templates_path.exists():
        raise FileNotFoundError(f"Templates directory does not exist: {templates_path}")

    template_files = sorted([p for p in templates_path.glob("*.xml")])
    if not template_files:
        raise FileNotFoundError("No .xml templates found in templates_dir")


    # prepare output
    run_id = uuid.uuid4().hex
    run_dir = Path(out_dir) / run_id
    run_dir.mkdir(parents=True, exist_ok=True)

    # safe parts
    safe_last = _sanitize_filename_part(pianist_last)
    safe_label_addition = _sanitize_filename_part(label_addition)
    label_base = f"{year}_{pianist_last}_{label_addition}" if label_addition else f"{year}_{pianist_last}"
    gnd_uri = f"https://d-nb.info/gnd/{gnd_uid}" if gnd_uid else ""

    generated_paths = []

    # produce 24 files, cycling templates if necessary
    for i in range(1, 25):
        tpl = template_files[(i - 1) % len(template_files)]
        tree = etree.parse(str(tpl))
        root = tree.getroot()

        # Find a manifestation element in the template (first occurrence)
        manifestations = root.xpath(".//mei:manifestation", namespaces=NS)
        if manifestations:
            m_el = manifestations[0]
            m_el.set("{http://www.w3.org/XML/1998/namespace}id", manifestation_id)
            m_el.set("label", label_base)
            m_el.set("n", str(manifestation_n))
            m_el.set("type", "audio_recording")
        else:
            # create a new manifestation element under manifestationList or sourceDesc
            M = "{http://www.music-encoding.org/ns/mei}"
            m_el = etree.Element(f"{M}manifestation")
            m_el.set("{http://www.w3.org/XML/1998/namespace}id", manifestation_id)
            m_el.set("label", label_base)
            m_el.set("n", str(manifestation_n))
            m_el.set("type", "audio_recording")
            src_list = root.xpath(".//mei:manifestationList", namespaces=NS)
            if src_list:
                src_list[0].append(m_el)
            else:
                src_desc = root.xpath(".//mei:sourceDesc", namespaces=NS)
                if src_desc:
                    ml = etree.SubElement(src_desc[0], "{http://www.music-encoding.org/ns/mei}manifestationList")
                    ml.append(m_el)
                else:
                    root.append(m_el)

        # inside the manifestation, find the bibl/persName role="pianist" and creation
        bibl = m_el.find(".//{http://www.music-encoding.org/ns/mei}bibl")
        if bibl is None:
            # create editionStmt/edition/bibl
            editionStmt = etree.SubElement(m_el, "{http://www.music-encoding.org/ns/mei}editionStmt")
            edition = etree.SubElement(editionStmt, "{http://www.music-encoding.org/ns/mei}edition")
            bibl = etree.SubElement(edition, "{http://www.music-encoding.org/ns/mei}bibl")

            # add title + identifier + singer (kept constant)
            title = etree.SubElement(bibl, "{http://www.music-encoding.org/ns/mei}title")
            title.text = "Winterreise : [Liederzyklus nach Gedichten von Wilhelm Müller; D 911 (op. 89)] / Franz Schubert"
            identifier = etree.SubElement(bibl, "{http://www.music-encoding.org/ns/mei}identifier")
            identifier.set("auth", "GND")
            identifier.set("auth.uri", "https://d-nb.info/990256839")
            pers_singer = etree.SubElement(bibl, "{http://www.music-encoding.org/ns/mei}persName")
            pers_singer.set("role", "singer")
            pers_singer.set("auth", "GND")
            pers_singer.set("auth.uri", "https://d-nb.info/gnd/118691457")
            pers_singer.text = "Fischer-Dieskau, Dietrich"

        # Update or create pianist persName
        pianists = bibl.xpath(".//mei:persName[@role='pianist']", namespaces=NS)
        if pianists:
            p_el = pianists[0]
            p_el.set("auth", "GND")
            if gnd_uri:
                p_el.set("auth.uri", gnd_uri)
            p_el.text = f"{pianist_last}, {pianist_first}"
        else:
            p_el = etree.SubElement(bibl, "{http://www.music-encoding.org/ns/mei}persName")
            p_el.set("role", "pianist")
            p_el.set("auth", "GND")
            if gnd_uri:
                p_el.set("auth.uri", gnd_uri)
            p_el.text = f"{pianist_last}, {pianist_first}"

        # Update or create creation element
        creation_cfg = CREATION_MAP.get(context, ("", context or ""))
        creations = bibl.xpath(".//mei:creation", namespaces=NS)
        if creations:
            c_el = creations[0]
            if creation_cfg[0]:
                c_el.set("type", creation_cfg[0])
            c_el.text = creation_cfg[1]
        else:
            c_el = etree.SubElement(bibl, "{http://www.music-encoding.org/ns/mei}creation")
            if creation_cfg[0]:
                c_el.set("type", creation_cfg[0])
            c_el.text = creation_cfg[1]

        # Insert appInfo into meiHead -> encodingDesc if present
        enc_desc = root.xpath(".//mei:meiHead//mei:encodingDesc", namespaces=NS)
        appinfo_fragment = _make_appinfo_fragment()
        if enc_desc:
            appinfo_els = enc_desc[0].xpath("./mei:appInfo", namespaces=NS)
            if appinfo_els:
                existing_appinfo = appinfo_els[0]
                application_el = appinfo_fragment.find("{http://www.music-encoding.org/ns/mei}application")
                existing_appinfo.append(application_el)
            else:
                enc_desc_el = enc_desc[0]
                enc_desc_el.append(appinfo_fragment)
        else:
            root.append(appinfo_fragment)

        # Write file
        outname = f"{year}_{_sanitize_filename_part(safe_last)}_{_sanitize_filename_part(safe_label_addition)}_{i}_Audio_Data.xml" if label_addition else f"{year}_{_sanitize_filename_part(safe_last)}_{i}_Audio_Data.xml"
        outpath = run_dir / outname
        tree.write(str(outpath), encoding="utf-8", xml_declaration=True, pretty_print=True)
        generated_paths.append(outpath)

    # Create ZIP
    zipname = f"{year}_{_sanitize_filename_part(safe_last)}_{_sanitize_filename_part(safe_label_addition)}.zip" if label_addition else f"{year}_{_sanitize_filename_part(safe_last)}.zip"
    zippath = TEMP_MEI_DIR / zipname
    with zipfile.ZipFile(str(zippath), "w", zipfile.ZIP_DEFLATED) as zf:
        for p in generated_paths:
            zf.write(p, arcname=p.name)

    # Create a preview string of the entire <meiHead> of the first file
    first_path = generated_paths[0]
    first_tree = etree.parse(str(first_path))
    first_root = first_tree.getroot()
    meihead_els = first_root.xpath(".//mei:meiHead", namespaces=NS)
    if meihead_els:
        meihead_str = etree.tostring(meihead_els[0], encoding="unicode", pretty_print=True)
    else:
        meihead_str = "<!-- meiHead not found in template -->"

    return str(zippath), meihead_str, generated_paths[0].name